"""
REST API for the news classifier.

    GET  /health   -> {"status": "ok", "model_loaded": true}
    POST /predict  {"text": "..."} -> {"label": "Sports", "confidence": 0.99}
    GET  /docs     -> interactive Swagger UI (generated by FastAPI automatically)

Model source:
    - default: local folder ./models/model (or MODEL_DIR env variable)
    - if MODEL_S3_URI is set (e.g. s3://my-bucket/news-classifier/model),
      the model is downloaded from S3 at startup first.

Run:  uvicorn api.main:app --port 8000
"""
import logging
import os
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

logging.basicConfig(level=logging.INFO)
log = logging.getLogger("api")

DEFAULT_MODEL_DIR = Path(__file__).resolve().parent.parent / "models" / "model"


# ---------- Request / response schemas (validated automatically by pydantic) ----------
class PredictRequest(BaseModel):
    text: str = Field(..., min_length=1, max_length=5000,
                      examples=["Oil prices rise as OPEC cuts production"])


class PredictResponse(BaseModel):
    label: str
    confidence: float


# ---------- Model loading ----------
def download_from_s3(s3_uri: str, target_dir: Path) -> Path:
    """Download every file under s3://bucket/prefix into target_dir."""
    import boto3  # imported lazily: only needed when S3 is used

    bucket, _, prefix = s3_uri.removeprefix("s3://").partition("/")
    s3 = boto3.client("s3")
    target_dir.mkdir(parents=True, exist_ok=True)
    for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket, Prefix=prefix):
        for obj in page.get("Contents", []):
            relative = obj["Key"][len(prefix):].lstrip("/")
            if relative:
                (target_dir / relative).parent.mkdir(parents=True, exist_ok=True)
                s3.download_file(bucket, obj["Key"], str(target_dir / relative))
    log.info("Downloaded model from %s to %s", s3_uri, target_dir)
    return target_dir


def load_model():
    """Return an object with a .predict(text) -> {"label", "confidence"} method."""
    from src.predict import NewsClassifier  # heavy import (torch), so done lazily

    model_dir = Path(os.getenv("MODEL_DIR", DEFAULT_MODEL_DIR))
    s3_uri = os.getenv("MODEL_S3_URI")
    if s3_uri:
        model_dir = download_from_s3(s3_uri, Path("/tmp/model"))
    log.info("Loading model from %s", model_dir)
    return NewsClassifier(model_dir)


# The model lives here. Tests replace it with a fake model.
state = {"model": None}


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Runs once at startup: load the model into memory (not on every request!)."""
    if state["model"] is None:
        try:
            state["model"] = load_model()
        except Exception:
            # Keep the server up so /health can report the problem (model_loaded=false)
            log.exception("Could not load model - /predict will return 503")
    yield


app = FastAPI(title="News Classifier API", version="1.0.0", lifespan=lifespan,
              description="Classifies news headlines into World, Sports, Business, Sci/Tech.")


@app.get("/health")
def health():
    """Used by Docker / load balancers / monitoring to check the service is alive."""
    return {"status": "ok", "model_loaded": state["model"] is not None}


@app.post("/predict", response_model=PredictResponse)
def predict(req: PredictRequest):
    if state["model"] is None:
        raise HTTPException(status_code=503, detail="Model not loaded")
    if not req.text.strip():
        raise HTTPException(status_code=422, detail="Text must not be empty")
    return state["model"].predict(req.text)
